-- Lançamentos (AP-020, ADR 0022): receitas e despesas de cada condomínio (ADR-002), ligadas à conta
-- analítica do plano de contas (0405), e opcionalmente ao centro de custo (0503), à conta bancária
-- (0504) e ao fornecedor (0201). Valores em centavos. Cancelamento = status inactive; exclusão lógica.
CREATE TABLE IF NOT EXISTS `erp_entries` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `condominium_id` int unsigned NOT NULL,
  `nature` enum('receita','despesa') NOT NULL,
  `chart_account_id` int unsigned NOT NULL,
  `cost_center_id` int unsigned DEFAULT NULL,
  `bank_account_id` int unsigned DEFAULT NULL COMMENT 'Obrigatória quando o lançamento está pago',
  `supplier_id` int unsigned DEFAULT NULL,
  `description` varchar(160) NOT NULL,
  `amount_cents` bigint unsigned NOT NULL,
  `competence` char(7) NOT NULL COMMENT 'Mês de competência AAAA-MM',
  `due_on` date NOT NULL,
  `paid_on` date DEFAULT NULL,
  `document_number` varchar(40) DEFAULT NULL,
  `notes` text DEFAULT NULL,
  `status` enum('active','inactive') NOT NULL DEFAULT 'active' COMMENT 'inactive = cancelado',
  `created_by` int unsigned DEFAULT NULL,
  `updated_by` int unsigned DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `deleted_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_erp_entries_condominium` (`condominium_id`, `deleted_at`, `status`, `due_on`),
  KEY `idx_erp_entries_competence` (`condominium_id`, `competence`),
  KEY `idx_erp_entries_account` (`chart_account_id`),
  KEY `idx_erp_entries_cost_center` (`cost_center_id`),
  KEY `idx_erp_entries_bank_account` (`bank_account_id`),
  KEY `idx_erp_entries_supplier` (`supplier_id`),
  CONSTRAINT `fk_erp_entries_condominium` FOREIGN KEY (`condominium_id`) REFERENCES `condominiums` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_entries_account` FOREIGN KEY (`chart_account_id`) REFERENCES `erp_chart_accounts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_entries_cost_center` FOREIGN KEY (`cost_center_id`) REFERENCES `erp_cost_centers` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_entries_bank_account` FOREIGN KEY (`bank_account_id`) REFERENCES `erp_bank_accounts` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_entries_supplier` FOREIGN KEY (`supplier_id`) REFERENCES `erp_suppliers` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_entries_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_erp_entries_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
