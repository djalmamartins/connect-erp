-- Operacional (AP-110 a AP-121, ADR 0051), pelo motor de cadastros: manutenções, ocorrências,
-- reservas de áreas comuns (sobre erp_common_areas, AP-008), lista de espera, seguros, contratos,
-- agendamentos de mudança e as configurações deles. Anexos pelo Disco Virtual (ADR 0047); ocorrência
-- pode abrir chamado na fila do Help Desk (ADR 0034, ticket_id). Idempotente (a suíte reaplica).
CREATE TABLE IF NOT EXISTS `erp_maintenances` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `condominium_id` int unsigned NOT NULL,
  `service` varchar(160) NOT NULL,
  `supplier_id` int unsigned DEFAULT NULL,
  `planned_on` date NOT NULL,
  `frequency` enum('unica','mensal','trimestral','semestral','anual') NOT NULL DEFAULT 'unica',
  `done_on` date DEFAULT NULL,
  `description` text DEFAULT NULL,
  `document_id` int unsigned DEFAULT NULL,
  `status` enum('active','running','done','inactive') NOT NULL DEFAULT 'active' COMMENT 'active = agendada',
  `created_by` int unsigned DEFAULT NULL,
  `updated_by` int unsigned DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `deleted_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_erp_maintenances_list` (`condominium_id`, `planned_on`, `deleted_at`),
  KEY `idx_erp_maintenances_supplier` (`supplier_id`),
  CONSTRAINT `fk_erp_maintenances_condominium` FOREIGN KEY (`condominium_id`) REFERENCES `condominiums` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_maintenances_supplier` FOREIGN KEY (`supplier_id`) REFERENCES `erp_suppliers` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_maintenances_document` FOREIGN KEY (`document_id`) REFERENCES `erp_documents` (`id`) ON DELETE RESTRICT,
  CONSTRAINT `fk_erp_maintenances_created_by` FOREIGN KEY (`created_by`) REFERENCES `users` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_erp_maintenances_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `users` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

